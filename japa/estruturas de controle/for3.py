# LIST COMPREHENSION
# UTILIZASSE DE UM LAÇO FOR PARA ITERAR E CRIAR ARRAYS/SUBARRAYS

array = list()
print(f'Array: {array} \nO array criado está vazio\n')

array = [numero for numero in range(5)] # [expressão for item in iteravel]
print(f'Array: {array} \nApós passar pela iteração foram criados novos elementos no array\n')
# expressão: valor adicionado à lista
# iteravel: percorre os elementos
